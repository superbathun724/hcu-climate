-- =========================================================
-- 09_survey.sql — 인식 변화 설문(사전·사후)과 최종 제출
--
-- 01~06, 08 다음, 07 앞에 돌린다. 03 을 고쳤으니 03 도 다시 돌린다(설문 전에는 게임을 막는 부분). (07 은 늘 마지막)  몇 번을 돌려도 같은 상태가 된다.
--
-- 흐름
--   1. 사전 설문: 로그인하면 먼저 낸다. 내기 전에는 게임을 할 수 없다(03 assert_surveyed).
--      배포(launch_at) 전에 가입한 계정은 late = true 로 표시한다(이미 게임을 해 본 사람이라 분석에서 따로 본다).
--   2. 관리자가 "최종 제출 열기"를 누르면, 학생은 사후 설문을 내면서 최종 제출을 한다.
--      그 순간의 점수(배포 뒤 보낸 코인 합, 배수 포함)가 최종 점수로 고정된다. 그 뒤로 더 해도 바뀌지 않는다.
--      사후 설문을 내지 않은 사람의 점수는 최종 집계에 들어가지 않는다(0점).
--   3. 관리자가 "최종 제출 닫기"를 누르면 최종 순위를 계산해 그대로 저장한다(final_results).
--      반: (제출한 사람 점수 합 + 반 방어 보너스) ÷ 반 인원(가입·메일 확인한 모든 사람)  ← 주간 순위와 같은 1인 평균
--      동아리: 제출한 사람 점수 합 ÷ 동아리 인원
--   교사 계정(교사 팀)도 똑같이 사전·사후 설문을 내고, 점수도 집계한다(is_teacher 로 구분해 분석할 수 있다).
--
-- 개인정보: 응답은 계정과 이어져 있어야 사전·사후를 짝지을 수 있다. 관리 화면과 내보내기에는
--   이메일 대신 계정 코드만 나온다(보안 기록과 같은 코드). 문항 답은 보안 기록에 남기지 않는다.
-- 문항 문구를 바꾸려면 아래 insert 의 body 를 고치고 이 파일을 다시 돌린다(id 는 바꾸지 않는다).
-- =========================================================

