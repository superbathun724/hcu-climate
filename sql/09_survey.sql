-- ---------- 내부 도우미 ----------
create or replace function public.final_state()
returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce((select value from public.app_settings where key = 'final'), '{"open": false, "closed": false}'::jsonb)
$$;

-- 배포 뒤 보낸 코인 합(배수 포함) = 학생 한 명의 점수
create or replace function public.player_score(p_user uuid)
returns bigint language sql stable security definer set search_path = public as $$
  select coalesce(sum(amount * mult), 0)::bigint from public.sends where user_id = p_user
$$;

create or replace function public.survey_questions_for(p_phase text)
returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object('id', id, 'kind', kind, 'area', area, 'body', body, 'required', required) order by pos), '[]'::jsonb)
    from public.survey_questions
   where phase = 'both' or (p_phase = 'post' and phase = 'post')
$$;

-- 최종 순위 계산 (닫을 때 저장한다)
create or replace function public.final_tally()
returns jsonb language sql stable security definer set search_path = public as $$
  with mem as (
    select p.user_id, p.class_id, p.club_id from public.profiles p join auth.users u on u.id = p.user_id
     where u.email_confirmed_at is not null),
  cls as (
    select c.id, coalesce(c.name, c.id || '반') as name, r.name as region,
           (select count(*) from mem where mem.class_id = c.id)::integer as members,
           (select count(*) from public.final_submissions f where f.class_id = c.id)::integer as submitted,
           (select coalesce(sum(score), 0) from public.final_submissions f where f.class_id = c.id)::bigint as score,
           (select coalesce(sum(points), 0) from public.rank_bonus b where b.class_id = c.id)::bigint as bonus
      from public.classes c left join public.regions r on r.id = c.region_id),
  clb as (
    select k.id, k.name,
           (select count(*) from mem where mem.club_id = k.id)::integer as members,
           (select count(*) from public.final_submissions f where f.club_id = k.id)::integer as submitted,
           (select coalesce(sum(score), 0) from public.final_submissions f where f.club_id = k.id)::bigint as score
      from public.clubs k)
  select jsonb_build_object(
    'classes', (select coalesce(jsonb_agg(to_jsonb(x) order by x.per_capita desc nulls last, x.id), '[]'::jsonb) from
                 (select cls.*, round((score + bonus)::numeric / nullif(members, 0), 1) as per_capita from cls) x),
    'clubs',   (select coalesce(jsonb_agg(to_jsonb(y) order by y.per_capita desc nulls last, y.name), '[]'::jsonb) from
                 (select clb.*, round(score::numeric / nullif(members, 0), 1) as per_capita from clb) y))
$$;

create or replace function public.survey_audit(p_user uuid, p_action text, p_detail jsonb)
returns void language plpgsql security definer set search_path = public as $$
begin
  if to_regprocedure('public.audit_write(uuid,text,jsonb)') is not null then
    execute 'select public.audit_write($1, $2, $3)' using p_user, p_action, p_detail;
  end if;
end;
$$;

-- ---------- 학생이 부르는 함수 ----------
-- 지금 내야 할 설문과 최종 제출 상태
create or replace function public.survey_state()
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid(); f jsonb := public.final_state();
  v_pre boolean; v_post boolean; v_need text; v_final record;
begin
  if v_uid is null then raise exception '로그인이 필요해요.' using errcode = '42501'; end if;
  v_pre  := exists (select 1 from public.survey_responses where user_id = v_uid and phase = 'pre');
  v_post := exists (select 1 from public.survey_responses where user_id = v_uid and phase = 'post');
  v_need := case when not v_pre then 'pre'
                 when (f ->> 'open')::boolean and not v_post then 'post' end;
  select score, submitted_at into v_final from public.final_submissions where user_id = v_uid;
  return jsonb_build_object(
    'pre_done', v_pre, 'post_done', v_post, 'need', v_need,
    'final_open', (f ->> 'open')::boolean, 'final_closed', (f ->> 'closed')::boolean,
    'score_now', public.player_score(v_uid),
    'final_score', v_final.score, 'final_at', v_final.submitted_at,
    'questions', case when v_need is null then '[]'::jsonb else public.survey_questions_for(v_need) end);
end;
$$;

-- 설문 내기. 사후 설문이면 최종 제출도 같이 한다.
create or replace function public.submit_survey(p_phase text, p_answers jsonb, p_ms integer default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid(); f jsonb := public.final_state();
  q record; v jsonb; clean jsonb := '{}'::jsonb; k text;
  v_prof record; v_late boolean; v_score bigint;
begin
  if v_uid is null then raise exception '로그인이 필요해요.' using errcode = '42501'; end if;
  if p_phase not in ('pre', 'post') then raise exception '설문 종류가 이상해요.'; end if;
  if exists (select 1 from public.players where user_id = v_uid and locked_at is not null) then
    raise exception '계정이 잠겨 있어요. 관리자에게 알려 주세요.' using errcode = 'P0001';
  end if;
  if exists (select 1 from public.survey_responses where user_id = v_uid and phase = p_phase) then
    raise exception '이미 낸 설문이에요.' using errcode = 'P0001';
  end if;
  if p_phase = 'post' then
    if not coalesce((f ->> 'open')::boolean, false) then raise exception '지금은 최종 제출 기간이 아니에요.' using errcode = 'P0001'; end if;
    if not exists (select 1 from public.survey_responses where user_id = v_uid and phase = 'pre') then
      raise exception '사전 설문을 먼저 해 주세요.' using errcode = 'P0001';
    end if;
  end if;
  if jsonb_typeof(p_answers) is distinct from 'object' then raise exception '답을 읽지 못했어요.'; end if;

  -- 모르는 문항 번호가 있으면 거부
  for k in select jsonb_object_keys(p_answers) loop
    if not exists (select 1 from public.survey_questions where id::text = k and (phase = 'both' or (p_phase = 'post' and phase = 'post'))) then
      raise exception '문항 번호가 이상해요: %', left(k, 10);
    end if;
  end loop;
  -- 문항마다 검사: 객관식은 0~5 정수(0 = 응답하지 않음), 주관식은 500자까지
  for q in select * from public.survey_questions where phase = 'both' or (p_phase = 'post' and phase = 'post') order by pos loop
    v := p_answers -> q.id::text;
    if q.kind = 'likert' then
      if v is null or jsonb_typeof(v) <> 'number' or (v #>> '{}')::numeric not in (0, 1, 2, 3, 4, 5) then
        if q.required then raise exception '%번 문항에 답해 주세요(“응답하지 않음”도 고를 수 있어요).', q.pos; end if;
        continue;
      end if;
      clean := clean || jsonb_build_object(q.id::text, (v #>> '{}')::integer);
    else
      if v is not null and jsonb_typeof(v) = 'string' and length(trim(v #>> '{}')) > 0 then
        clean := clean || jsonb_build_object(q.id::text, left(trim(v #>> '{}'), 500));
      end if;
    end if;
  end loop;

  select p.class_id, p.club_id, u.created_at into v_prof
    from public.profiles p join auth.users u on u.id = p.user_id where p.user_id = v_uid;
  v_late := v_prof.created_at < coalesce(((select value from public.app_settings where key = 'launch_at') #>> '{}')::timestamptz, now());

  insert into public.survey_responses (user_id, phase, answers, duration_ms, late, class_id, club_id, is_teacher)
  values (v_uid, p_phase, clean, greatest(least(coalesce(p_ms, 0), 86400000), 0), v_late,
          v_prof.class_id, v_prof.club_id, v_prof.class_id = 8);

  if p_phase = 'post' then
    v_score := public.player_score(v_uid);
    insert into public.final_submissions (user_id, class_id, club_id, score) values (v_uid, v_prof.class_id, v_prof.club_id, v_score);
    perform public.survey_audit(v_uid, 'final_submit', jsonb_build_object('score', v_score));
  else
    perform public.survey_audit(v_uid, 'survey_pre', jsonb_build_object('late', v_late));
  end if;
  return jsonb_build_object('ok', true, 'phase', p_phase, 'score', v_score);
end;
$$;

-- 최종 결과 (닫힌 뒤에 누구나 본다)
create or replace function public.final_results()
returns jsonb language sql stable security definer set search_path = public as $$
  select case when (public.final_state() ->> 'closed')::boolean then
    (select jsonb_build_object('closed_at', closed_at, 'classes', classes, 'clubs', clubs)
       from public.final_results order by id desc limit 1) end
$$;

-- ---------- 관리자 함수 ----------
-- 최종 제출 열기·닫기. 닫으면 그때 순위를 저장한다. 다시 열 수도 있다(닫을 때 새로 저장).
create or replace function public.admin_final_set(p_open boolean)
returns jsonb language plpgsql security definer set search_path = public as $$
declare t jsonb;
begin
  if not public.admin_gate('admin_final_set') then return jsonb_build_object('error', '관리자만, 2단계 인증을 한 뒤에 할 수 있어요.'); end if;
  if p_open then
    update public.app_settings set value = '{"open": true, "closed": false}'::jsonb, updated_at = now() where key = 'final';
    perform public.survey_audit(auth.uid(), 'final_open', '{}'::jsonb);
    return jsonb_build_object('open', true);
  end if;
  t := public.final_tally();
  insert into public.final_results (classes, clubs) values (t -> 'classes', t -> 'clubs');
  update public.app_settings set value = '{"open": false, "closed": true}'::jsonb, updated_at = now() where key = 'final';
  perform public.survey_audit(auth.uid(), 'final_close',
    jsonb_build_object('submitted', (select count(*) from public.final_submissions)));
  return jsonb_build_object('open', false, 'closed', true, 'result', t);
end;
$$;

-- 설문 결과 요약: 응답 수, 문항별 사전·사후 평균(0 = 응답하지 않음은 빼고), 둘 다 낸 사람끼리 비교
create or replace function public.admin_survey_summary()
returns jsonb language plpgsql security definer set search_path = public as $$
declare r jsonb;
begin
  if not public.admin_gate('admin_survey_summary') then return jsonb_build_object('error', '관리자만, 2단계 인증을 한 뒤에 할 수 있어요.'); end if;
  with pre as (select * from public.survey_responses where phase = 'pre'),
       post as (select * from public.survey_responses where phase = 'post'),
       paired as (select pre.user_id, pre.answers a1, post.answers a2 from pre join post using (user_id))
  select jsonb_build_object(
    'final', public.final_state(),
    'members', (select count(*) from public.profiles p join auth.users u on u.id = p.user_id where u.email_confirmed_at is not null),
    'pre', (select count(*) from pre), 'post', (select count(*) from post), 'paired', (select count(*) from paired),
    'late', (select count(*) from pre where late), 'teachers', (select count(*) from pre where is_teacher),
    'fast', (select count(*) from public.survey_responses where duration_ms < 30000),
    'by_class', (select coalesce(jsonb_agg(jsonb_build_object('class_id', c.id, 'name', coalesce(c.name, c.id || '반'),
                    'pre', (select count(*) from pre where pre.class_id = c.id),
                    'post', (select count(*) from post where post.class_id = c.id)) order by c.id), '[]'::jsonb)
                 from public.classes c),
    'items', (select coalesce(jsonb_agg(jsonb_build_object(
                'id', q.id, 'pos', q.pos, 'area', q.area, 'body', q.body, 'phase', q.phase,
                'pre_mean',  (select round(avg((answers ->> q.id::text)::numeric), 2) from pre  where (answers ->> q.id::text)::numeric between 1 and 5),
                'pre_n',     (select count(*) from pre  where (answers ->> q.id::text)::numeric between 1 and 5),
                'post_mean', (select round(avg((answers ->> q.id::text)::numeric), 2) from post where (answers ->> q.id::text)::numeric between 1 and 5),
                'post_n',    (select count(*) from post where (answers ->> q.id::text)::numeric between 1 and 5),
                'paired_n',  (select count(*) from paired where (a1 ->> q.id::text)::numeric between 1 and 5 and (a2 ->> q.id::text)::numeric between 1 and 5),
                'paired_change', (select round(avg((a2 ->> q.id::text)::numeric - (a1 ->> q.id::text)::numeric), 2) from paired
                                   where (a1 ->> q.id::text)::numeric between 1 and 5 and (a2 ->> q.id::text)::numeric between 1 and 5)
              ) order by q.pos), '[]'::jsonb)
              from public.survey_questions q where q.kind = 'likert')
  ) into r;
  return r;
end;
$$;

-- 분석용 내보내기: 사람마다 한 줄. 이메일 없이 계정 코드(보안 기록과 같은 코드)
create or replace function public.admin_survey_export()
returns table (code text, class_id smallint, club text, is_teacher boolean, late boolean,
               pre_answers jsonb, pre_ms integer, pre_at timestamptz,
               post_answers jsonb, post_ms integer, post_at timestamptz, final_score bigint)
language plpgsql security definer set search_path = public as $$
begin
  if not public.admin_gate('admin_survey_export') then return; end if;
  return query
    select left(md5('hcu-audit:' || pre.user_id::text), 8), pre.class_id, k.name, pre.is_teacher, pre.late,
           pre.answers, pre.duration_ms, pre.submitted_at,
           post.answers, post.duration_ms, post.submitted_at, f.score
      from public.survey_responses pre
      left join public.survey_responses post on post.user_id = pre.user_id and post.phase = 'post'
      left join public.final_submissions f on f.user_id = pre.user_id
      left join public.clubs k on k.id = pre.club_id
     where pre.phase = 'pre'
     order by pre.class_id, pre.submitted_at;
end;
