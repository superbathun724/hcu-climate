-- ---------- 응답 ----------
create table if not exists public.survey_responses (
  user_id      uuid not null references auth.users(id) on delete cascade,
  phase        text not null check (phase in ('pre', 'post')),
  answers      jsonb not null,            -- {"1": 4, "2": 0, "10": "폭염"}  (0 = 응답하지 않음)
  duration_ms  integer,                   -- 설문 화면을 연 뒤 제출까지 (너무 짧으면 분석에서 거를 수 있게)
  late         boolean not null default false,   -- 배포 전에 가입한 계정
  class_id     smallint,
  club_id      smallint,
  is_teacher   boolean not null default false,
  submitted_at timestamptz not null default now(),
  primary key (user_id, phase)
);

-- ---------- 최종 제출 (사후 설문을 낸 순간의 점수) ----------
create table if not exists public.final_submissions (
  user_id      uuid primary key references auth.users(id) on delete cascade,
  class_id     smallint,
  club_id      smallint,
  score        bigint not null,
  submitted_at timestamptz not null default now()
);

-- ---------- 설정과 최종 결과 ----------
create table if not exists public.app_settings (
  key        text primary key,
  value      jsonb not null,
  updated_at timestamptz not null default now()
);
insert into public.app_settings (key, value) values
  ('launch_at', to_jsonb(now())),
  ('final', '{"open": false, "closed": false}'::jsonb)
