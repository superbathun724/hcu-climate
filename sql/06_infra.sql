-- ==========================================================
-- 06_infra.sql — 지역 기금과 시설 (반 투표로 짓기)
--
-- 05_voice.sql 다음에 실행. 몇 번을 돌려도 같은 상태가 됩니다.
--
-- 흐름
--   1. 지역에 보낸 코인은 먼저 대비율을 채운다(상한 150%, 방파제를 올리면 더).
--      상한을 넘친 만큼은 버려지지 않고 그 지역의 "기금"이 된다(재난 중이면 2배로).  → 03_game.sql send_coins
--   2. 그 지역을 맡은 반 학생(바누아투는 교사 팀)이 다음에 지을 시설에 투표한다. 한 사람 한 표, 언제든 바꿀 수 있다.
--   3. 가장 많은 표를 받은 시설이 최소 표(3표, 반 인원이 더 적으면 인원 수)를 넘고 기금이 모이면 저절로 지어진다.
--      표는 지어진 뒤에도 남아서, 마음을 바꾸지 않으면 같은 시설의 다음 단계를 계속 짓는다.
--   4. 지으면 그 반 순위에 점수가 들어가고, 시설마다 효과가 생긴다.
--
-- 시설 (각 5단계, 숫자를 바꾸려면 아래 함수만)
--   warning  조기경보 시스템  재난이 깎는 대비율 30% → 단계마다 10%씩 덜 깎임 (5단계면 15%)
--   wall     방파제·제방 강화 대비율 상한 150% → 단계마다 +20% (5단계면 250%)
--   shelter  대피소           재난 방어 성공 보너스 1인당 10점 → 단계마다 +5점 (5단계면 35점)
--   지을 때마다 그 반 순위에 1인당 20 × 단계 점수
--   값: 10,000 → 20,000 → 40,000 → 80,000 → 160,000 기금 (단계마다 2배)
-- ==========================================================

-- ---------- 표 ----------
alter table public.regions add column if not exists fund numeric(14,2) not null default 0 check (fund >= 0);

create table if not exists public.infra_types (
  key   text primary key,
  name  text not null,
  sort  smallint not null
);
insert into public.infra_types (key, name, sort) values
  ('warning', '조기경보 시스템', 1),
  ('wall',    '방파제·제방 강화', 2),
  ('shelter', '대피소', 3)
on conflict (key) do update set name = excluded.name, sort = excluded.sort;

create table if not exists public.region_infra (
  region_id smallint not null references public.regions(id),
  key       text     not null references public.infra_types(key),
  level     smallint not null default 0 check (level between 0 and 5),
  primary key (region_id, key)
);
insert into public.region_infra (region_id, key)
select r.id, t.key from public.regions r cross join public.infra_types t
on conflict do nothing;

-- 한 사람 한 표 (자기 반이 맡은 지역에만)
create table if not exists public.infra_votes (
  user_id   uuid primary key references auth.users(id) on delete cascade,
  region_id smallint not null references public.regions(id),
  key       text     not null references public.infra_types(key),
  voted_at  timestamptz not null default now()
);
create index if not exists infra_votes_region_idx on public.infra_votes (region_id, key);

-- 지은 기록 (화면 알림·순위 점수)
create table if not exists public.infra_builds (
  id        bigint generated by default as identity primary key,
  region_id smallint not null references public.regions(id),
  key       text     not null references public.infra_types(key),
  level     smallint not null,
  cost      integer  not null,
  built_at  timestamptz not null default now()
);

-- 순위 보너스: 재난 방어(disaster_id) 또는 시설 건설(build_id)
alter table public.rank_bonus alter column disaster_id drop not null;
alter table public.rank_bonus add column if not exists build_id bigint references public.infra_builds(id) on delete cascade;
create unique index if not exists rank_bonus_build_uq on public.rank_bonus (class_id, build_id);


-- ---------- 숫자 (바꾸려면 여기만) ----------
create or replace function public.infra_max_level() returns integer language sql immutable as $$ select 5 $$;
-- 다음 단계(1~5)를 짓는 값
create or replace function public.infra_cost(p_level integer)
returns integer language sql immutable as $$ select (10000 * power(2, greatest(p_level, 1) - 1))::integer $$;
create or replace function public.infra_min_votes() returns integer language sql immutable as $$ select 3 $$;
create or replace function public.infra_build_points_pc() returns integer language sql immutable as $$ select 20 $$;

create or replace function public.infra_level(p_region smallint, p_key text)
returns integer language sql stable security definer set search_path = public as $$
  select coalesce((select level from public.region_infra where region_id = p_region and key = p_key), 0)
$$;

-- 효과: 대비율 상한, 재난이 깎는 양, 방어 보너스 (03_game.sql 이 부른다)
create or replace function public.region_cap(p_region smallint)
returns numeric language sql stable security definer set search_path = public as $$
  select public.shield_max() + 20 * public.infra_level(p_region, 'wall')
$$;
create or replace function public.region_drain(p_region smallint)
returns numeric language sql stable security definer set search_path = public as $$
  select round(public.disaster_drain() * (1 - 0.1 * public.infra_level(p_region, 'warning')), 1)
$$;
create or replace function public.region_defense_bonus_pc(p_region smallint)
returns integer language sql stable security definer set search_path = public as $$
  select public.defense_bonus_pc() + 5 * public.infra_level(p_region, 'shelter')
$$;

-- 메일 인증까지 마친 반 인원
create or replace function public.class_members(p_class smallint)
returns integer language sql stable security definer set search_path = public as $$
  select count(*)::integer from public.profiles p join auth.users u on u.id = p.user_id
   where p.class_id = p_class and u.email_confirmed_at is not null
$$;


-- ---------- 짓기 ----------
-- 표가 가장 많은 시설을, 최소 표를 넘고 기금이 되면 짓는다. 기금이 남으면 계속.
-- 지은 것들을 돌려준다(화면 알림용).
create or replace function public.try_build(p_region smallint)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_class smallint; v_members integer; v_need integer;
  v_key text; v_votes integer; v_lv integer; v_cost integer; v_fund numeric;
  v_build bigint; v_out jsonb := '[]'::jsonb;
begin
  select id into v_class from public.classes where region_id = p_region;
  if v_class is null then return v_out; end if;
  v_members := public.class_members(v_class);
  v_need := least(public.infra_min_votes(), greatest(v_members, 1));

  loop
    -- 아직 최고 단계가 아닌 시설 중 표가 가장 많은 것 (같으면 순서대로)
    select v.key, count(*)::integer into v_key, v_votes
      from public.infra_votes v
      join public.infra_types t on t.key = v.key
     where v.region_id = p_region and public.infra_level(p_region, v.key) < public.infra_max_level()
     group by v.key, t.sort
     order by count(*) desc, t.sort
     limit 1;
    exit when v_key is null or v_votes < v_need;

    v_lv := public.infra_level(p_region, v_key) + 1;
    v_cost := public.infra_cost(v_lv);
    select fund into v_fund from public.regions where id = p_region for update;
    exit when v_fund < v_cost;

    update public.regions set fund = fund - v_cost where id = p_region;
    update public.region_infra set level = v_lv where region_id = p_region and key = v_key;
    insert into public.infra_builds (region_id, key, level, cost) values (p_region, v_key, v_lv, v_cost)
      returning id into v_build;
    insert into public.rank_bonus (class_id, build_id, points)
      values (v_class, v_build, public.infra_build_points_pc() * v_lv * v_members)
      on conflict do nothing;
    v_out := v_out || jsonb_build_object('key', v_key, 'name', (select name from public.infra_types where key = v_key), 'level', v_lv);
    v_key := null;
  end loop;
  return v_out;
end;
$$;

-- 투표: 자기 반이 맡은 지역의 시설에만. 같은 시설에 다시 누르면 표를 거둔다.
create or replace function public.vote_infra(p_key text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_uid uuid := auth.uid(); v_region smallint; v_cur text; v_built jsonb;
begin
  if v_uid is null then raise exception '로그인이 필요해요.' using errcode = '42501'; end if;
  perform public.assert_unlocked(v_uid);
  select c.region_id into v_region from public.profiles p join public.classes c on c.id = p.class_id where p.user_id = v_uid;
  if v_region is null then raise exception '우리 반이 맡은 지역이 없어요.' using errcode = 'P0001'; end if;
  if not exists (select 1 from public.infra_types where key = p_key) then
    raise exception '시설을 찾을 수 없어요.' using errcode = 'P0001';
  end if;

  select key into v_cur from public.infra_votes where user_id = v_uid;
  if v_cur = p_key then
    delete from public.infra_votes where user_id = v_uid;
  else
    insert into public.infra_votes (user_id, region_id, key) values (v_uid, v_region, p_key)
    on conflict (user_id) do update set region_id = excluded.region_id, key = excluded.key, voted_at = now();
  end if;
  v_built := public.try_build(v_region);
  return jsonb_build_object('built', v_built) || public.infra_state(v_region);
end;
$$;

-- 화면용: 한 지역의 기금·시설·표 (내 표 포함). 투표는 그 지역을 맡은 반만 할 수 있다(can_vote).
create or replace function public.infra_state(p_region smallint)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v_class smallint; v_my text; v_myregion smallint;
begin
  if auth.uid() is null then raise exception '로그인이 필요해요.' using errcode = '42501'; end if;
  select id into v_class from public.classes where region_id = p_region;
  select key into v_my from public.infra_votes where user_id = auth.uid() and region_id = p_region;
  select c.region_id into v_myregion from public.profiles p join public.classes c on c.id = p.class_id where p.user_id = auth.uid();
  return jsonb_build_object(
    'region_id', p_region,
    'fund', (select fund from public.regions where id = p_region),
    'cap', public.region_cap(p_region),
    'drain', public.region_drain(p_region),
    'defense_pc', public.region_defense_bonus_pc(p_region),
    'need_votes', least(public.infra_min_votes(), greatest(coalesce(public.class_members(v_class), 0), 1)),
    'can_vote', v_myregion = p_region,
    'my_vote', v_my,
    'items', (select jsonb_agg(jsonb_build_object(
                 'key', t.key, 'name', t.name, 'level', ri.level, 'max', public.infra_max_level(),
                 'cost', case when ri.level < public.infra_max_level() then public.infra_cost(ri.level + 1) end,
                 'votes', (select count(*) from public.infra_votes v where v.region_id = p_region and v.key = t.key))
               order by t.sort)
                from public.infra_types t join public.region_infra ri on ri.key = t.key and ri.region_id = p_region));
end;
$$;

-- 화면용: 모든 지역의 시설 단계와 기금 (지원 탭 카드, 게임 배경)
create or replace function public.infra_all()
returns table (region_id smallint, fund numeric, cap numeric, warning smallint, wall smallint, shelter smallint)
language sql stable security definer set search_path = public as $$
  select r.id, r.fund, public.region_cap(r.id),
         (select level from public.region_infra where region_id = r.id and key = 'warning'),
         (select level from public.region_infra where region_id = r.id and key = 'wall'),
         (select level from public.region_infra where region_id = r.id and key = 'shelter')
    from public.regions r order by r.id
$$;


-- ---------- 접근 권한 ----------
alter table public.infra_types  enable row level security;
alter table public.region_infra enable row level security;
alter table public.infra_votes  enable row level security;
alter table public.infra_builds enable row level security;
grant select on public.infra_types, public.region_infra, public.infra_builds to authenticated;
drop policy if exists infra_types_read on public.infra_types;
create policy infra_types_read on public.infra_types for select to authenticated using (true);
drop policy if exists region_infra_read on public.region_infra;
create policy region_infra_read on public.region_infra for select to authenticated using (true);
drop policy if exists infra_builds_read on public.infra_builds;
create policy infra_builds_read on public.infra_builds for select to authenticated using (true);
revoke all on public.infra_votes from anon, authenticated;            -- 누가 무엇에 투표했는지는 안 보인다. 숫자만(infra_state)

revoke execute on function public.try_build(smallint)        from public, anon, authenticated;
revoke execute on function public.vote_infra(text)           from public, anon;
revoke execute on function public.infra_state(smallint)      from public, anon;
revoke execute on function public.infra_all()                from public, anon;
grant  execute on function public.vote_infra(text)           to authenticated;
grant  execute on function public.infra_state(smallint)      to authenticated;
grant  execute on function public.infra_all()                to authenticated;

