-- ---------- 학교 이메일 도메인 ----------
-- 도메인이 바뀌면 여기 한 곳만 고친다.
create or replace function public.school_domain()
returns text language sql immutable as $$ select 'hcu.hs.kr' $$;

-- "아이디@hcu.hs.kr" 정확히 그 모양만 통과.
-- 'a@b@hcu.hs.kr', 'a@evil.hcu.hs.kr', 'a@hcu.hs.kr.evil.com' 은 모두 거부.
create or replace function public.is_school_email(p_email text)
returns boolean language sql immutable as $$
  select coalesce(lower(p_email) ~ ('^[^@\s]+@' || replace(public.school_domain(), '.', '\.') || '$'), false)
$$;


-- ---------- 학생·교사 구분 ----------
-- 학생 이메일의 @ 앞은 "2510 + 1학년 반번호 3자리"(예: 2510609). 이 모양이면 학생이다.
-- 숫자로만 된 다른 아이디(다른 학년)는 받지 않는다. 숫자가 아닌 아이디는 교사로 본다.
-- 학년이 바뀌면 여기 한 곳만 고친다.
create or replace function public.student_id_pattern()
returns text language sql immutable as $$ select '^2510[0-9]{3}$' $$;

-- 'student' | 'teacher' | 'other'(숫자 아이디지만 이 학년이 아님)
create or replace function public.email_role(p_email text)
returns text language sql immutable as $$
  select case
    when split_part(lower(p_email), '@', 1) ~ public.student_id_pattern() then 'student'
    when split_part(lower(p_email), '@', 1) ~ '^[0-9]+$' then 'other'
    else 'teacher' end
$$;


-- ---------- 지역 (반마다 하나씩 돕는 바깥 지역) ----------
-- shield = 대비율(%). 50 이상이면 재난을 버틴다. 코인으로만 오른다(뒤 파일에서).
create table if not exists public.regions (
  id         smallint primary key,
  name       text not null unique,
  hazard     text not null,
  shield     numeric(5,1) not null default 0 check (shield between 0 and 100),
  updated_at timestamptz not null default now()
);

-- ---------- 반 ----------
create table if not exists public.classes (
  id        smallint primary key check (id between 1 and 20),
  region_id smallint not null unique references public.regions(id)
);

-- ---------- 동아리 ----------
