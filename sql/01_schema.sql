-- ---------- 학생 프로필 ----------
-- 수집 항목 최소: 이메일은 auth.users 에 이미 있으므로 여기 다시 두지 않는다.
-- 반·동아리는 가입 때 한 번 정하고, 학생은 바꿀 수 없다 (update 권한 없음).
create table if not exists public.profiles (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  class_id   smallint not null references public.classes(id),
  club_id    smallint not null references public.clubs(id),
  created_at timestamptz not null default now()
);
create index if not exists profiles_class_idx on public.profiles (class_id);
create index if not exists profiles_club_idx  on public.profiles (club_id);


-- ---------- 관리자 ----------
-- 이 표에 있는 계정만 관리자. 학생은 이 표를 읽지도 쓰지도 못한다.
-- 등록은 맨 아래 SQL 을 SQL Editor 에서 직접 실행.
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

create or replace function public.is_admin()
returns boolean
language sql stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.admins where user_id = auth.uid())
$$;

-- 관리자이면서 이번 로그인에서 2단계 인증(휴대폰 인증 앱의 6자리)까지 마쳤는가.
-- 관리자 기능은 전부 이것을 본다. 비밀번호만 털려서는 관리 기능을 쓸 수 없다.
-- (aal2 = Supabase 가 "2단계까지 확인한 로그인"에 붙이는 표시. 토큰 안에 있어 위조할 수 없다)
create or replace function public.admin_ok()
returns boolean
language sql stable
security definer
set search_path = public
as $$
  select public.is_admin() and coalesce(auth.jwt() ->> 'aal', '') = 'aal2'
$$;


-- ==========================================================
-- 가입 검사
--
-- 화면은 supabase.auth.signUp() 에 이렇게 보낸다:
--   options: { data: { class_id: 2, club_id: 5 } }
-- 그 값은 auth.users.raw_user_meta_data 에 들어오고, 이 트리거가
-- 검사한 뒤 profiles 에 한 줄을 만든다. 하나라도 틀리면 예외를 던지고,
-- 그러면 auth.users 에 넣던 것까지 통째로 취소된다(계정이 안 생긴다).
-- ==========================================================
create or replace function public.on_signup()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_class smallint;
  v_club  smallint;
  v_role  text;
  v_teacher_class boolean;
begin
  if not public.is_school_email(new.email) then
    raise exception '학교 이메일(@%)로만 가입할 수 있어요.', public.school_domain()
      using errcode = 'P0001';
  end if;

  begin
    v_class := (new.raw_user_meta_data ->> 'class_id')::smallint;
    v_club  := (new.raw_user_meta_data ->> 'club_id')::smallint;
  exception when others then
    raise exception '반과 동아리를 다시 골라 주세요.' using errcode = 'P0001';
  end;

  if v_class is null or not exists (select 1 from public.classes where id = v_class) then
    raise exception '반을 다시 골라 주세요.' using errcode = 'P0001';
  end if;
  if v_club is null or not exists (select 1 from public.clubs where id = v_club) then
    raise exception '동아리를 다시 골라 주세요.' using errcode = 'P0001';
  end if;

  -- 학생은 학생 반·동아리만, 교사는 "교사" 반만 (동아리는 지도하는 동아리를 골라도 된다)
  v_role := public.email_role(new.email);
  if v_role = 'other' then
    raise exception '이 게임은 아이디가 2510으로 시작하는 학생과 선생님만 참여할 수 있어요.' using errcode = 'P0001';
  end if;
  v_teacher_class := exists (select 1 from public.classes where id = v_class and name = '교사');
  if v_role = 'student' and v_teacher_class then
    raise exception '학생은 "교사" 반을 고를 수 없어요. 내 반을 골라 주세요.' using errcode = 'P0001';
  end if;
  if v_role = 'student' and exists (select 1 from public.clubs where id = v_club and name = '교사') then
    raise exception '학생은 "교사" 동아리를 고를 수 없어요. 내 동아리를 골라 주세요.' using errcode = 'P0001';
  end if;
  if v_role = 'teacher' and not v_teacher_class then
    raise exception '선생님은 반에서 "교사"를 골라 주세요.' using errcode = 'P0001';
  end if;

  insert into public.profiles (user_id, class_id, club_id)
  values (new.id, v_class, v_club);
  return new;
end;
$$;

drop trigger if exists on_signup on auth.users;
create trigger on_signup
  after insert on auth.users
  for each row execute function public.on_signup();

-- 가입한 뒤 이메일을 다른 도메인으로 바꾸는 길도 막는다.
create or replace function public.on_email_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.email is distinct from old.email and not public.is_school_email(new.email) then
    raise exception '학교 이메일(@%)로만 바꿀 수 있어요.', public.school_domain()
      using errcode = 'P0001';
  end if;
  -- 학생 ↔ 교사가 바뀌는 이메일 변경은 막는다(교사 반에 학생이 들어가는 길)
  if new.email is distinct from old.email and public.email_role(new.email) <> public.email_role(old.email) then
    raise exception '학생·교사 구분이 바뀌는 이메일로는 바꿀 수 없어요.' using errcode = 'P0001';
  end if;
  return new;
end;
$$;

drop trigger if exists on_email_change on auth.users;
create trigger on_email_change
  before update of email on auth.users
  for each row execute function public.on_email_change();


-- ==========================================================
-- 접근 권한
--
-- 프로젝트를 "새 표 자동 공개 끔"으로 만들었으므로, 여기서 연 것만 열린다.
-- 학생 쪽(anon·authenticated)에는 읽기만 준다. 쓰기는 이후 파일의
-- 서버 함수 안에서만 일어난다 (voca-web execute_trade 와 같은 방식).
-- ==========================================================
alter table public.regions  enable row level security;
alter table public.classes  enable row level security;
alter table public.clubs    enable row level security;
alter table public.profiles enable row level security;
alter table public.admins   enable row level security;

-- 지역·반·동아리: 로그인 전 가입 화면에서도 목록이 필요하다.
grant select on public.regions, public.classes, public.clubs to anon, authenticated;

drop policy if exists regions_read on public.regions;
create policy regions_read on public.regions for select to anon, authenticated using (true);
drop policy if exists classes_read on public.classes;
create policy classes_read on public.classes for select to anon, authenticated using (true);
drop policy if exists clubs_read on public.clubs;
create policy clubs_read on public.clubs for select to anon, authenticated using (true);

-- 프로필: 자기 것만 읽는다. 남의 반·동아리를 개별로 볼 길은 없다.
grant select on public.profiles to authenticated;
drop policy if exists profiles_read_own on public.profiles;
create policy profiles_read_own on public.profiles
  for select to authenticated using (user_id = auth.uid());

-- 관리자 표: 아무 권한도 주지 않는다. is_admin() 으로만 물어본다.
revoke all on public.admins from anon, authenticated;

-- 함수: Postgres 는 새 함수를 누구나 실행할 수 있게 만든다. 필요한 것만 다시 연다.
revoke execute on function public.on_signup()        from public, anon, authenticated;
revoke execute on function public.on_email_change()  from public, anon, authenticated;
revoke execute on function public.is_admin()         from public, anon;
grant  execute on function public.is_admin()         to authenticated;
revoke execute on function public.admin_ok()         from public, anon;
grant  execute on function public.admin_ok()         to authenticated;


