-- ---------- 단어장 ----------
create table if not exists public.word_sets (
  id         bigint generated by default as identity primary key,
  name       text not null unique check (char_length(name) between 1 and 60),
  hidden     boolean not null default false,     -- 학생 화면에서만 감춘다. 단어·진도는 그대로
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ---------- 단어 ----------
-- 열 모양은 voca-web 과 같다. CSV 형식이 같으므로 그대로 옮겨 담는다.
create table if not exists public.words (
  id        bigint generated by default as identity primary key,
  set_id    bigint not null references public.word_sets(id) on delete cascade,
  position  integer not null default 0,            -- CSV 에 적힌 순서
  word      text not null check (char_length(word) between 1 and 100),
  senses    jsonb not null default '[]'::jsonb,
  notes     jsonb not null default '[]'::jsonb,
  synonyms  jsonb not null default '[]'::jsonb,
  antonyms  jsonb not null default '[]'::jsonb,
  phrases   jsonb not null default '[]'::jsonb,
  sentences jsonb not null default '[]'::jsonb,
  unique (set_id, word)                            -- 덮어쓸 때 같은 단어를 찾는 열쇠
);
create index if not exists words_set_idx on public.words (set_id, position);

-- 삭제는 바로 지우지 않고 7일 동안 "삭제 대기"로 둔다(관리자 계정을 뺏겨도 되돌릴 수 있게).
-- 그동안 학생에게는 안 보이고, 관리자가 복구할 수 있다. 7일이 지나면 단어·진도까지 지운다.
alter table public.word_sets add column if not exists deleted_at timestamptz;

-- ---------- 학습 진도 (voca-web progress 그대로) ----------
-- 학생마다 따로. 단어가 지워지면 그 단어의 진도도 같이 지워진다.
-- 이미 받은 코인은 별도 장부(이후 파일)에 있으므로 지워지지 않는다.
-- 쓰기는 5단계의 서버 채점 함수 안에서만 한다.
create table if not exists public.progress (
  user_id        uuid   not null references auth.users(id) on delete cascade,
  word_id        bigint not null references public.words(id) on delete cascade,
  srs_level      smallint not null default 0,
  next_review_at timestamptz,
  attempt_count  integer not null default 0,
  wrong_count    integer not null default 0,
  last_tested_at timestamptz,
  primary key (user_id, word_id)
);
create index if not exists progress_due_idx on public.progress (user_id, next_review_at);


-- ==========================================================
-- 읽기 권한
-- ==========================================================
alter table public.word_sets enable row level security;
alter table public.words     enable row level security;
alter table public.progress  enable row level security;

grant select on public.word_sets, public.words, public.progress to authenticated;
revoke insert, update, delete on public.word_sets, public.words, public.progress from anon, authenticated;

drop policy if exists word_sets_read on public.word_sets;
create policy word_sets_read on public.word_sets
  for select to authenticated
  using ((not hidden and deleted_at is null) or public.is_admin());

drop policy if exists words_read on public.words;
create policy words_read on public.words
  for select to authenticated
  using (exists (select 1 from public.word_sets s
                  where s.id = set_id and ((not s.hidden and s.deleted_at is null) or public.is_admin())));

drop policy if exists progress_read_own on public.progress;
create policy progress_read_own on public.progress
  for select to authenticated
  using (user_id = auth.uid());


-- ==========================================================
-- 관리자 함수
-- ==========================================================

-- 관리자가 아니면 여기서 멈춘다. 모든 admin_ 함수의 첫 줄.
create or replace function public.require_admin()
returns void language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_admin() then
    raise exception '관리자만 할 수 있어요.' using errcode = '42501';
  end if;
  if not public.admin_ok() then
    raise exception '관리자 2단계 인증을 먼저 해 주세요(관리 화면 맨 위).' using errcode = 'P0001';
  end if;
end;
$$;

-- 이름 다듬기: 앞뒤 공백 제거, 비었거나 너무 길면 거부
create or replace function public.clean_set_name(p_name text)
returns text language plpgsql immutable as $$
declare v text := btrim(coalesce(p_name, ''));
begin
  if char_length(v) = 0  then raise exception '단어장 이름을 적어 주세요.' using errcode = 'P0001'; end if;
  if char_length(v) > 60 then raise exception '단어장 이름은 60자까지예요.' using errcode = 'P0001'; end if;
  return v;
end;
$$;


-- ---------- CSV 올리기 (새로 만들기 또는 덮어쓰기) ----------
-- p_words: [{word, senses, notes, synonyms, antonyms, phrases, sentences}, …]
--          화면의 js/csv.js 가 CSV 를 이 모양으로 바꿔서 보낸다.
-- 같은 이름의 단어장이 있으면 덮어쓴다:
--   - CSV 에 있는 단어 : 내용을 새 것으로 (같은 단어면 학생 진도는 유지)
--   - CSV 에 새로 생긴 단어 : 추가
--   - CSV 에서 빠진 단어 : 삭제 (그 단어의 진도도 삭제)
-- 같은 단어가 CSV 에 두 번 있으면 뒤의 것을 쓴다.
create or replace function public.admin_upload_set(p_name text, p_words jsonb)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_name    text := public.clean_set_name(p_name);
  v_set     bigint;
  v_created boolean := false;
  v_rows    integer;
  v_added   integer;
  v_changed integer;
  v_removed integer;
begin
  perform public.require_admin();

  if jsonb_typeof(p_words) is distinct from 'array' then
    raise exception '단어 목록이 비어 있어요.' using errcode = 'P0001';
  end if;
  v_rows := jsonb_array_length(p_words);
  if v_rows = 0    then raise exception '단어 목록이 비어 있어요.' using errcode = 'P0001'; end if;
  if v_rows > 1000 then raise exception '한 번에 1,000줄까지 올릴 수 있어요.' using errcode = 'P0001'; end if;

  perform public.purge_deleted_sets();
  select id into v_set from public.word_sets where name = v_name for update;
  if v_set is null then
    insert into public.word_sets (name) values (v_name) returning id into v_set;
    v_created := true;
  else
    -- 삭제 대기 중인 같은 이름이면 덮어쓰면서 되살린다
    update public.word_sets set updated_at = now(), deleted_at = null where id = v_set;
  end if;

  -- CSV 를 표 모양으로. 같은 단어는 마지막 줄만 남긴다.
  create temp table _incoming on commit drop as
  select distinct on (w.word) w.*
  from (
    select btrim(e->>'word')                           as word,
           (ord - 1)::integer                          as position,
           coalesce(e->'senses',    '[]'::jsonb)       as senses,
           coalesce(e->'notes',     '[]'::jsonb)       as notes,
           coalesce(e->'synonyms',  '[]'::jsonb)       as synonyms,
           coalesce(e->'antonyms',  '[]'::jsonb)       as antonyms,
           coalesce(e->'phrases',   '[]'::jsonb)       as phrases,
           coalesce(e->'sentences', '[]'::jsonb)       as sentences
    from jsonb_array_elements(p_words) with ordinality as t(e, ord)
  ) w
  where w.word is not null and w.word <> ''
  order by w.word, w.position desc;

  if exists (select 1 from _incoming where char_length(word) > 100) then
    raise exception '100자가 넘는 단어가 있어요.' using errcode = 'P0001';
  end if;
  if not exists (select 1 from _incoming) then
    raise exception '단어 칸이 모두 비어 있어요.' using errcode = 'P0001';
  end if;

  delete from public.words w
   where w.set_id = v_set
     and not exists (select 1 from _incoming i where i.word = w.word);
  get diagnostics v_removed = row_count;

  select count(*) into v_changed
    from _incoming i join public.words w on w.set_id = v_set and w.word = i.word;

  insert into public.words (set_id, position, word, senses, notes, synonyms, antonyms, phrases, sentences)
  select v_set, position, word, senses, notes, synonyms, antonyms, phrases, sentences from _incoming
  on conflict (set_id, word) do update
    set position  = excluded.position,
        senses    = excluded.senses,
        notes     = excluded.notes,
        synonyms  = excluded.synonyms,
        antonyms  = excluded.antonyms,
        phrases   = excluded.phrases,
        sentences = excluded.sentences;

  select count(*) - v_changed into v_added from _incoming;
  drop table _incoming;

  return jsonb_build_object(
    'set_id', v_set, 'name', v_name, 'created', v_created,
    'added', v_added, 'updated', v_changed, 'removed', v_removed);
end;
$$;


-- ---------- 이름 바꾸기 ----------
create or replace function public.admin_rename_set(p_set bigint, p_name text)
returns void
language plpgsql security definer set search_path = public as $$
declare v_name text := public.clean_set_name(p_name);
begin
  perform public.require_admin();
  if exists (select 1 from public.word_sets where name = v_name and id <> p_set) then
    raise exception '같은 이름의 단어장이 이미 있어요.' using errcode = 'P0001';
  end if;
  update public.word_sets set name = v_name, updated_at = now() where id = p_set;
  if not found then raise exception '단어장을 찾을 수 없어요.' using errcode = 'P0001'; end if;
end;
$$;

-- ---------- 숨기기 / 다시 보이기 ----------
create or replace function public.admin_set_hidden(p_set bigint, p_hidden boolean)
returns void
language plpgsql security definer set search_path = public as $$
begin
  perform public.require_admin();
  update public.word_sets set hidden = coalesce(p_hidden, false), updated_at = now() where id = p_set;
  if not found then raise exception '단어장을 찾을 수 없어요.' using errcode = 'P0001'; end if;
end;
$$;

-- ---------- 삭제 (7일 대기) / 복구 ----------
-- 삭제하면 7일 동안 학생에게서 사라지고, 그 뒤 단어와 학생 진도가 같이 지워진다.
-- 7일이 지난 것은 관리자가 단어장 함수를 쓸 때 정리한다(cron 없이).
create or replace function public.purge_deleted_sets()
returns void
language sql security definer set search_path = public as $$
  delete from public.word_sets where deleted_at < now() - interval '7 days'
$$;

create or replace function public.admin_delete_set(p_set bigint)
returns void
language plpgsql security definer set search_path = public as $$
begin
  perform public.require_admin();
  perform public.purge_deleted_sets();
  update public.word_sets set deleted_at = coalesce(deleted_at, now()), updated_at = now() where id = p_set;
  if not found then raise exception '단어장을 찾을 수 없어요.' using errcode = 'P0001'; end if;
end;
$$;

create or replace function public.admin_restore_set(p_set bigint)
returns void
language plpgsql security definer set search_path = public as $$
begin
  perform public.require_admin();
  perform public.purge_deleted_sets();
  update public.word_sets set deleted_at = null, updated_at = now() where id = p_set and deleted_at is not null;
  if not found then raise exception '복구할 단어장을 찾을 수 없어요(7일이 지났을 수 있어요).' using errcode = 'P0001'; end if;
end;
$$;


-- ---------- 함수 실행 권한 ----------
-- Postgres 는 새 함수를 누구나 실행할 수 있게 만든다. 로그인한 사람만 부르게 하고,
-- 관리자인지는 함수 안의 require_admin() 이 다시 본다.
revoke execute on function public.require_admin()                  from public, anon;
revoke execute on function public.admin_upload_set(text, jsonb)     from public, anon;
revoke execute on function public.admin_rename_set(bigint, text)    from public, anon;
revoke execute on function public.admin_set_hidden(bigint, boolean) from public, anon;
revoke execute on function public.admin_delete_set(bigint)          from public, anon;
revoke execute on function public.admin_restore_set(bigint)         from public, anon;
revoke execute on function public.purge_deleted_sets()              from public, anon, authenticated;
grant  execute on function public.admin_upload_set(text, jsonb)     to authenticated;
grant  execute on function public.admin_rename_set(bigint, text)    to authenticated;
grant  execute on function public.admin_set_hidden(bigint, boolean) to authenticated;
grant  execute on function public.admin_delete_set(bigint)          to authenticated;
grant  execute on function public.admin_restore_set(bigint)         to authenticated;


