-- 01_schema.sql 다음에 SQL Editor 에서 실행. 몇 번을 돌려도 같은 상태가 됩니다.
-- (voca-web 01_schema·02_rls 를 가져와 정리: 사용자별 단어장 → 학교 공용 단어장)
--
-- 권한
--   학생   : 숨기지 않은 단어장과 그 단어를 읽기만. 자기 진도만 읽기.
--   관리자 : 아래 admin_… 함수로만 바꾼다. 표에 직접 쓰는 권한은 아무에게도 없다.
--            관리자인지는 함수 안에서 is_admin() 으로 서버가 판단한다.
