-- 진행 중인 재난을 시간만큼 반영하고, 때가 됐으면 새 재난을 일으킨다.
-- 여러 학생이 동시에 불러도 한 명만 실제로 돈다(나머지는 건너뜀).
create or replace function public.world_tick()
returns void language plpgsql security definer set search_path = public as $$
declare d public.disasters; v_should numeric; v_delta numeric;
begin
  if not pg_try_advisory_xact_lock(424242) then return; end if;

  for d in select * from public.disasters where drained < drain loop
    v_should := d.drain * least(1, greatest(0,
                  extract(epoch from (now() - d.starts_at)) / extract(epoch from (d.ends_at - d.starts_at))));
    v_delta := round(v_should - d.drained, 3);
    if v_delta > 0 then
      update public.regions set shield = greatest(0, shield - v_delta), updated_at = now() where id = d.region_id;
      update public.disasters set drained = drained + v_delta where id = d.id;
    end if;
  end loop;

  if not exists (select 1 from public.disasters where starts_at > now() - public.disaster_every()) then
    insert into public.disasters (region_id, starts_at, ends_at, drain)
    select r.id, now(), now() + public.disaster_length(), public.disaster_drain()
      from public.regions r
     where r.id is distinct from (select region_id from public.disasters order by starts_at desc limit 1)
     order by random() limit 1;
  end if;
end;
$$;

-- 화면용: 지금 재난(없으면 null)과 다음 재난까지 남은 시간
create or replace function public.current_event()
returns jsonb language plpgsql security definer set search_path = public as $$
declare d public.disasters; r public.regions; v_next timestamptz;
begin
  if auth.uid() is null then raise exception '로그인이 필요해요.' using errcode = '42501'; end if;
  perform public.world_tick();
  select * into d from public.disasters where ends_at > now() order by starts_at desc limit 1;
  select max(starts_at) + public.disaster_every() into v_next from public.disasters;
  if d.id is null then
    return jsonb_build_object('active', false, 'next_at', v_next);
  end if;
  select * into r from public.regions where id = d.region_id;
  return jsonb_build_object(
    'active', true, 'id', d.id, 'region_id', d.region_id, 'region_name', r.name, 'hazard', r.hazard,
    'starts', d.starts_at, 'ends', d.ends_at, 'drain', d.drain, 'drained', d.drained,
    'shield', r.shield, 'mult', public.disaster_mult(), 'next_at', v_next);
end;
$$;


