-- ==========================================================
-- 03_game.sql — 탭, 코인 지갑, 지원(코인 보내기), 순위
--
-- 02_words.sql 다음에 SQL Editor 에서 실행. 몇 번을 돌려도 같은 상태가 됩니다.
--
-- 원칙 (voca-web execute_trade 와 같은 방식)
--   코인·대비율은 학생이 직접 쓸 수 있는 표가 아니다.
--   바뀌는 길은 이 파일의 함수뿐이고, 함수가 사용자를 auth.uid() 로 직접 확인한다.
--   브라우저가 보낸 "코인 몇 개" 같은 숫자는 믿지 않는다. 브라우저는 "몇 번 눌렀다"만 보내고,
--   그 횟수도 서버가 속도로 한 번 더 자른다.
--
-- 아직 정하지 않은 것 (정해지면 이 파일에서 숫자만 바꾼다)
--   - 재난 2배: 지금은 항상 1배. send_coins 의 v_mult
--   - 대비율 매일 감소: 아직 없음
-- ==========================================================


-- 한국 날짜. 하루 기록은 전부 이 날짜로 끊는다(UTC 로 끊으면 오전 9시에 하루가 바뀐다).
create or replace function public.kst_today()
returns date language sql stable as $$ select (now() at time zone 'Asia/Seoul')::date $$;


-- ---------- 지갑 (학생 한 명당 한 줄) ----------
create table if not exists public.players (
  user_id      uuid primary key references auth.users(id) on delete cascade,
  balance      numeric(14,4) not null default 0 check (balance >= 0),  -- 탭 효율이 0.5·0.25… 라 소수
  earned_taps  numeric(14,4) not null default 0,
  earned_words numeric(14,4) not null default 0,
  sent         bigint        not null default 0,
  tap_day      date,
  taps_today   integer       not null default 0,
  last_tap_at  timestamptz
);

-- ---------- 보낸 기록 (순위의 근거) ----------
-- 반·동아리를 보낼 때 같이 적는다. 한 번 보내면 반 순위와 동아리 순위에 동시에 들어간다.
create table if not exists public.sends (
  id        bigint generated by default as identity primary key,
  user_id   uuid     not null references auth.users(id) on delete cascade,
  class_id  smallint not null references public.classes(id),
  club_id   smallint not null references public.clubs(id),
  region_id smallint not null references public.regions(id),
  amount    integer  not null check (amount > 0),
  mult      smallint not null default 1,
  sent_at   timestamptz not null default now()
);
create index if not exists sends_class_idx  on public.sends (class_id, sent_at);
create index if not exists sends_club_idx   on public.sends (club_id, sent_at);
create index if not exists sends_region_idx on public.sends (region_id);

-- 대비율은 작은 송금(코인 1개 = 0.05%)도 잃지 않게 소수 셋째 자리까지 담는다.
alter table public.regions alter column shield type numeric(7,3);

alter table public.players enable row level security;
alter table public.sends   enable row level security;
revoke all on public.players, public.sends from anon, authenticated;   -- 아래 함수로만


-- ==========================================================
-- 숫자 (게임 규칙)
-- ==========================================================

-- 탭: 구간마다 길이 2배, 효율 절반. 1~300번 1코인, ~900번 0.5, ~2,100번 0.25 …
create or replace function public.tap_band() returns integer language sql immutable as $$ select 300 $$;

-- 사람이 낼 수 있는 속도. 1초에 15번, 한 번에 모아 보낼 수 있는 시간은 최대 10초.
create or replace function public.tap_speed() returns integer language sql immutable as $$ select 15 $$;

-- 코인 몇 개가 대비율 1% 인가 (un-summit DEF_PER_PCT 20 을 그대로 가져옴)
create or replace function public.coins_per_pct() returns integer language sql immutable as $$ select 20 $$;


-- 오늘 start 번 누른 상태에서 n 번 더 누르면 받는 코인
create or replace function public.tap_coins(p_start integer, p_n integer)
returns numeric language plpgsql immutable as $$
declare
  band   integer := public.tap_band();
  pos    integer := greatest(p_start, 0);
  left_n integer := greatest(p_n, 0);
  k      integer; b_start bigint; b_len bigint; take integer;
  coins  numeric := 0;
begin
  while left_n > 0 loop
    -- pos 가 속한 구간 k: 구간 k 는 band*(2^k - 1) 에서 시작, 길이 band*2^k
    k := floor(log(2, (pos::numeric / band) + 1))::integer;
    b_start := band * (power(2, k)::bigint - 1);
    b_len   := band * power(2, k)::bigint;
    if pos >= b_start + b_len then k := k + 1; b_start := b_start + b_len; b_len := b_len * 2; end if;
    take := least(left_n, (b_start + b_len - pos)::integer);
    coins := coins + take / power(2, k)::numeric;
    pos := pos + take;
    left_n := left_n - take;
  end loop;
  return coins;
end;
$$;

-- 지금 한 번 누를 때의 효율
create or replace function public.tap_rate(p_taps integer)
returns numeric language sql immutable as $$
  select 1 / power(2, floor(log(2, (greatest(p_taps,0)::numeric / public.tap_band()) + 1)))::numeric
$$;


-- ==========================================================
-- 함수
-- ==========================================================

-- 지갑이 없으면 만든다 (가입 직후 첫 접속). 코인 0, 탭 0 에서 시작.
create or replace function public.ensure_player(p_user uuid)
returns void language sql security definer set search_path = public as $$
  insert into public.players (user_id) values (p_user) on conflict do nothing;
$$;

-- 내 상태: 코인, 오늘 탭 수, 지금 효율
create or replace function public.my_state()
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_uid uuid := auth.uid(); p public.players;
begin
  if v_uid is null then raise exception '로그인이 필요해요.' using errcode = '42501'; end if;
  perform public.ensure_player(v_uid);
  select * into p from public.players where user_id = v_uid;
  if p.tap_day is distinct from public.kst_today() then p.taps_today := 0; end if;
  return jsonb_build_object(
    'balance', p.balance, 'taps_today', p.taps_today,
    'rate', public.tap_rate(p.taps_today), 'sent', p.sent);
end;
$$;

-- 탭 올리기. 브라우저는 2초쯤마다 모아서 "n번 눌렀다"를 보낸다.
-- 서버는 지난번 이후 흐른 시간으로 n 을 한 번 더 자른다(매크로 방지). 하루 한도는 없다.
create or replace function public.submit_taps(p_n integer)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  p public.players;
  v_today date := public.kst_today();
  v_elapsed numeric; v_allowed integer; v_take integer; v_coins numeric;
begin
  if v_uid is null then raise exception '로그인이 필요해요.' using errcode = '42501'; end if;
  perform public.ensure_player(v_uid);
  select * into p from public.players where user_id = v_uid for update;

  if p.tap_day is distinct from v_today then p.taps_today := 0; end if;

  v_elapsed := least(extract(epoch from (now() - coalesce(p.last_tap_at, now() - interval '10 seconds'))), 10);
  v_allowed := floor(v_elapsed * public.tap_speed())::integer + 5;
  v_take    := greatest(0, least(coalesce(p_n, 0), v_allowed, 500));
  v_coins   := public.tap_coins(p.taps_today, v_take);

  update public.players set
    tap_day     = v_today,
    taps_today  = p.taps_today + v_take,
    balance     = balance + v_coins,
    earned_taps = earned_taps + v_coins,
    last_tap_at = case when v_take > 0 then now() else last_tap_at end
  where user_id = v_uid
  returning * into p;

  return jsonb_build_object(
    'accepted', v_take, 'balance', p.balance, 'taps_today', p.taps_today,
    'rate', public.tap_rate(p.taps_today));
end;
$$;

-- 코인 보내기. 울산(자기 쪽)에는 쓸 수 없다 — 받을 수 있는 곳은 regions 표의 바깥 지역뿐이다.
create or replace function public.send_coins(p_region smallint, p_amount integer)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_prof public.profiles;
  v_bal numeric;
  v_mult smallint := 1;          -- 재난 2배는 재난 이벤트를 붙일 때 여기서 정한다
  v_shield numeric;
begin
  if v_uid is null then raise exception '로그인이 필요해요.' using errcode = '42501'; end if;
  if p_amount is null or p_amount < 1 then raise exception '1코인 이상 보내 주세요.' using errcode = 'P0001'; end if;
  if p_amount > 1000000 then raise exception '한 번에 너무 많이 보낼 수 없어요.' using errcode = 'P0001'; end if;
  if not exists (select 1 from public.regions where id = p_region) then
    raise exception '지역을 찾을 수 없어요.' using errcode = 'P0001';
  end if;

  select * into v_prof from public.profiles where user_id = v_uid;
  if v_prof is null then raise exception '계정 정보를 찾을 수 없어요.' using errcode = 'P0001'; end if;

  perform public.ensure_player(v_uid);
  select balance into v_bal from public.players where user_id = v_uid for update;
  if v_bal < p_amount then
    raise exception '코인이 부족해요. 지금 %코인 있어요.', floor(v_bal) using errcode = 'P0001';
  end if;

  update public.players set balance = balance - p_amount, sent = sent + p_amount where user_id = v_uid;

  update public.regions
     set shield = least(100, shield + (p_amount * v_mult)::numeric / public.coins_per_pct()),
         updated_at = now()
   where id = p_region
  returning shield into v_shield;

  insert into public.sends (user_id, class_id, club_id, region_id, amount, mult)
  values (v_uid, v_prof.class_id, v_prof.club_id, p_region, p_amount, v_mult);

  return jsonb_build_object(
    'balance', (select balance from public.players where user_id = v_uid),
    'region', p_region, 'shield', v_shield, 'mult', v_mult);
end;
$$;


-- ---------- 순위 기간 ----------
-- 순위는 기간마다 새로 시작한다. 단위를 바꾸려면 아래 'week' 한 단어만 바꾼다:
--   'day'   매일 0시(한국)          'week'  매주 월요일 0시(한국)          'month'  매달 1일 0시(한국)
-- 대비율(지역)과 지갑은 기간과 상관없이 쌓인다. 기간이 끊는 것은 순위 숫자뿐이다.
create or replace function public.rank_unit() returns text language sql immutable as $$ select 'week' $$;

create or replace function public.rank_window()
returns table (starts timestamptz, ends timestamptz, unit text)
language sql stable as $$
  with t as (select date_trunc(public.rank_unit(), now() at time zone 'Asia/Seoul') as local_start)
  select local_start at time zone 'Asia/Seoul',
         (local_start + ('1 ' || public.rank_unit())::interval) at time zone 'Asia/Seoul',
         public.rank_unit()
    from t
$$;

-- 화면용: 이번 기간 시작·끝 (남은 시간 표시)
create or replace function public.rank_round()
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object('starts', starts, 'ends', ends, 'unit', unit) from public.rank_window()
$$;

-- ---------- 순위: 이번 기간에 보낸 코인의 1인당 평균 ----------
-- 분모는 가입한 학생 수. 인원이 적은 팀도 1등을 할 수 있다.
-- 개인 이름·이메일은 돌려주지 않는다. 팀 단위 숫자만.
create or replace function public.rank_classes()
returns table (class_id smallint, region_name text, members integer, sent bigint, sent_today bigint, per_capita numeric)
language sql stable security definer set search_path = public as $$
  with w as (select starts, ends from public.rank_window()),
  t as (
    select c.id, r.name,
           (select count(*) from public.profiles p where p.class_id = c.id)::integer as m,
           coalesce((select sum(amount) from public.sends s, w
                      where s.class_id = c.id and s.sent_at >= w.starts and s.sent_at < w.ends), 0)::bigint as sent,
           coalesce((select sum(amount) from public.sends s where s.class_id = c.id
                      and (s.sent_at at time zone 'Asia/Seoul')::date = public.kst_today()), 0)::bigint as today
      from public.classes c join public.regions r on r.id = c.region_id)
  select id, name, m, sent, today, round(sent::numeric / nullif(m, 0), 1) from t
  order by 6 desc nulls last, 1;
$$;

create or replace function public.rank_clubs()
returns table (club_id smallint, club_name text, members integer, sent bigint, per_capita numeric)
language sql stable security definer set search_path = public as $$
  with w as (select starts, ends from public.rank_window()),
  t as (
    select k.id, k.name,
           (select count(*) from public.profiles p where p.club_id = k.id)::integer as m,
           coalesce((select sum(amount) from public.sends s, w
                      where s.club_id = k.id and s.sent_at >= w.starts and s.sent_at < w.ends), 0)::bigint as sent
      from public.clubs k)
  select id, name, m, sent, round(sent::numeric / nullif(m, 0), 1) from t
  order by 5 desc nulls last, 2;
$$;


