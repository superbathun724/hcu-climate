-- ==========================================================
-- 03_game.sql — 탭, 코인 지갑, 지원(코인 보내기), 재난 이벤트, 계정 잠금, 순위
--
-- 02_words.sql 다음에 SQL Editor 에서 실행. 몇 번을 돌려도 같은 상태가 됩니다.
--
-- 원칙 (voca-web execute_trade 와 같은 방식)
--   코인·대비율은 학생이 직접 쓸 수 있는 표가 아니다.
--   바뀌는 길은 이 파일의 함수뿐이고, 함수가 사용자를 auth.uid() 로 직접 확인한다.
--   브라우저가 보낸 "코인 몇 개" 같은 숫자는 믿지 않는다. 브라우저는 "몇 번 눌렀다"만 보내고,
--   그 횟수도 서버가 속도로 한 번 더 자른다.
--
-- 재난 이벤트 (cron 없이 돈다)
--   학생 화면이 15초마다 current_event() 를 부른다. 그때 world_tick() 이
--     - 진행 중인 재난이 그 지역 대비율을 시간에 따라 조금씩 쓰게 하고
--     - 마지막 재난이 시작된 지 disaster_every() 가 지났으면 새 재난을 하나 일으킨다.
--   아무도 접속하지 않으면 재난도 멈춘다(학생이 없는 밤에 혼자 깎이지 않는다).
--   재난 중인 지역에 보낸 코인은 2배로 들어간다.
--
-- 계정 잠금 (매크로 의심)
--   화면이 누르는 패턴(같은 자리에 너무 빠르게, 너무 일정한 간격)을 보고 submit_taps 에 알리거나,
--   서버가 "사람 속도보다 훨씬 많이 보냄"을 1분 안에 3번 보면 잠근다.
--   잠긴 계정은 탭·지원·단어 코인·건의·공감이 모두 막히고, 관리자가 풀어야 다시 쓸 수 있다.
-- ==========================================================


-- 한국 날짜. 하루 기록은 전부 이 날짜로 끊는다(UTC 로 끊으면 오전 9시에 하루가 바뀐다).
create or replace function public.kst_today()
returns date language sql stable as $$ select (now() at time zone 'Asia/Seoul')::date $$;


-- ---------- 지갑 (학생 한 명당 한 줄) ----------
create table if not exists public.players (
  user_id      uuid primary key references auth.users(id) on delete cascade,
  balance      numeric(14,4) not null default 0 check (balance >= 0),  -- 탭 효율이 0.5·0.25… 라 소수
  earned_taps  numeric(14,4) not null default 0,
  earned_words numeric(14,4) not null default 0,
  sent         bigint        not null default 0,
  tap_day      date,
  taps_today   integer       not null default 0,
  last_tap_at  timestamptz
);
alter table public.players add column if not exists locked_at   timestamptz;   -- 잠긴 때 (null = 정상)
alter table public.players add column if not exists lock_reason text;
alter table public.players add column if not exists strikes     integer not null default 0;  -- 서버 속도 경고 횟수
alter table public.players add column if not exists strike_at   timestamptz;
-- 화면이 매크로 같다고 알린 경우 바로 잠그지 않고 잠깐 쉬게 한다(사람이 리듬 타며 누르다 걸려도 손해가 작게).
alter table public.players add column if not exists tap_pause_until timestamptz;

-- ---------- 보낸 기록 (순위의 근거) ----------
-- 반·동아리를 보낼 때 같이 적는다. 한 번 보내면 반 순위와 동아리 순위에 동시에 들어간다.
create table if not exists public.sends (
  id        bigint generated by default as identity primary key,
  user_id   uuid     not null references auth.users(id) on delete cascade,
  class_id  smallint not null references public.classes(id),
  club_id   smallint not null references public.clubs(id),
  region_id smallint not null references public.regions(id),
  amount    integer  not null check (amount > 0),
  mult      smallint not null default 1,
  sent_at   timestamptz not null default now()
);
create index if not exists sends_class_idx  on public.sends (class_id, sent_at);
create index if not exists sends_club_idx   on public.sends (club_id, sent_at);
create index if not exists sends_region_idx on public.sends (region_id);

-- ---------- 재난 ----------
create table if not exists public.disasters (
  id        bigint generated by default as identity primary key,
  region_id smallint not null references public.regions(id),
  starts_at timestamptz not null,
  ends_at   timestamptz not null,
  drain     numeric(7,3) not null,              -- 이 재난이 쓰는 대비율 (%p)
  drained   numeric(7,3) not null default 0     -- 지금까지 쓴 만큼
);
create index if not exists disasters_start_idx on public.disasters (starts_at desc);

-- ---------- 잠금 기록 (관리자에게 보고) ----------
create table if not exists public.flags (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references auth.users(id) on delete cascade,
  reason      text not null,
  detail      jsonb,
  created_at  timestamptz not null default now(),
  resolved_at timestamptz,
  resolved_by uuid
);
create index if not exists flags_open_idx on public.flags (resolved_at, created_at);

-- 대비율은 작은 송금(코인 1개 = 0.05%)도 잃지 않게 소수 셋째 자리까지 담는다.
-- 100% 를 넘어도 계속 쌓인다(비축). 재난이 오면 이 비축분부터 쓰인다.
alter table public.regions alter column shield type numeric(7,3);
alter table public.regions drop constraint if exists regions_shield_check;
alter table public.regions drop constraint if exists regions_shield_nonneg;
alter table public.regions add constraint regions_shield_nonneg check (shield >= 0);

alter table public.players   enable row level security;
alter table public.sends     enable row level security;
alter table public.disasters enable row level security;
alter table public.flags     enable row level security;
revoke all on public.players, public.sends, public.disasters, public.flags from anon, authenticated;   -- 아래 함수로만


-- ==========================================================
-- 숫자 (게임 규칙) — 바꾸려면 여기만
-- ==========================================================

-- 탭: 구간마다 길이 2배, 효율 절반. 1~300번 1코인, ~900번 0.5, ~2,100번 0.25 …
create or replace function public.tap_band() returns integer language sql immutable as $$ select 300 $$;

-- 사람이 낼 수 있는 속도. 1초에 15번, 한 번에 모아 보낼 수 있는 시간은 최대 10초.
create or replace function public.tap_speed() returns integer language sql immutable as $$ select 15 $$;

-- 하루에 사람이 낼 수 없는 누른 횟수. 넘으면 봇으로 보고 잠근다(관리자가 풀 수 있다).
-- 8만 번 = 초당 5번으로 4시간 반을 쉬지 않고 눌러야 하는 양. 사람은 닿지 않고,
-- API 를 직접 부르는 봇은 하루 종일 돌리면 걸린다. 효율이 구간마다 절반이라
-- 봇이 이 아래에서 멈춰도 열심히 하는 학생과 코인 차이가 크지 않다.
create or replace function public.tap_day_max() returns integer language sql immutable as $$ select 80000 $$;
-- 화면이 매크로 같다고 알렸을 때: 몇 분 쉬게 할지, 24시간 안에 몇 번째면 잠글지
create or replace function public.tap_pause_min()     returns integer language sql immutable as $$ select 5 $$;
create or replace function public.tap_flags_to_lock() returns integer language sql immutable as $$ select 3 $$;

-- 코인 몇 개가 대비율 1% 인가 (un-summit DEF_PER_PCT 20 을 그대로 가져옴)
create or replace function public.coins_per_pct() returns integer language sql immutable as $$ select 20 $$;

-- 재난: 몇 분마다, 몇 분 동안, 대비율을 얼마나 쓰는가
create or replace function public.disaster_every()  returns interval language sql immutable as $$ select interval '8 minutes' $$;
create or replace function public.disaster_length() returns interval language sql immutable as $$ select interval '4 minutes' $$;
create or replace function public.disaster_drain()  returns numeric  language sql immutable as $$ select 6::numeric $$;
create or replace function public.disaster_mult()   returns smallint language sql immutable as $$ select 2::smallint $$;


-- 오늘 start 번 누른 상태에서 n 번 더 누르면 받는 코인
create or replace function public.tap_coins(p_start integer, p_n integer)
returns numeric language plpgsql immutable as $$
declare
  band   integer := public.tap_band();
  pos    integer := greatest(p_start, 0);
  left_n integer := greatest(p_n, 0);
  k      integer; b_start bigint; b_len bigint; take integer;
  coins  numeric := 0;
begin
  while left_n > 0 loop
    -- pos 가 속한 구간 k: 구간 k 는 band*(2^k - 1) 에서 시작, 길이 band*2^k
    k := floor(log(2, (pos::numeric / band) + 1))::integer;
    b_start := band * (power(2, k)::bigint - 1);
    b_len   := band * power(2, k)::bigint;
    if pos >= b_start + b_len then k := k + 1; b_start := b_start + b_len; b_len := b_len * 2; end if;
    take := least(left_n, (b_start + b_len - pos)::integer);
    coins := coins + take / power(2, k)::numeric;
    pos := pos + take;
    left_n := left_n - take;
  end loop;
  return coins;
end;
$$;

-- 지금 한 번 누를 때의 효율
create or replace function public.tap_rate(p_taps integer)
returns numeric language sql immutable as $$
  select 1 / power(2, floor(log(2, (greatest(p_taps,0)::numeric / public.tap_band()) + 1)))::numeric
$$;


-- ==========================================================
-- 계정 잠금
-- ==========================================================

create or replace function public.ensure_player(p_user uuid)
returns void language sql security definer set search_path = public as $$
  insert into public.players (user_id) values (p_user) on conflict do nothing;
$$;

-- 잠그고 관리자에게 보고(flags). 이미 잠겨 있으면 기록만 하나 더.
create or replace function public.lock_player(p_user uuid, p_reason text, p_detail jsonb)
returns void language plpgsql security definer set search_path = public as $$
begin
  perform public.ensure_player(p_user);
  update public.players set locked_at = coalesce(locked_at, now()), lock_reason = p_reason where user_id = p_user;
  insert into public.flags (user_id, reason, detail) values (p_user, p_reason, p_detail);
end;
$$;

-- 잠긴 계정이면 여기서 멈춘다. 코인이 생기거나 쓰이는 모든 함수의 첫 줄.
create or replace function public.assert_unlocked(p_user uuid)
returns void language plpgsql stable security definer set search_path = public as $$
begin
  if exists (select 1 from public.players where user_id = p_user and locked_at is not null) then
    raise exception '계정이 잠겨 있어요. 관리자에게 알려 주세요.' using errcode = 'P0001';
  end if;
end;
$$;

-- 관리자: 잠긴 계정 목록. 누구인지 알아야 풀 수 있으므로 여기서만 이메일을 보여 준다.
create or replace function public.admin_locked()
returns table (user_id uuid, email text, class_id smallint, club_name text, locked_at timestamptz,
               reason text, detail jsonb, flags integer)
language plpgsql stable security definer set search_path = public as $$
begin
  perform public.require_admin();
  return query
  select p.user_id, u.email::text, pr.class_id, c.name, p.locked_at, p.lock_reason,
         (select f.detail from public.flags f where f.user_id = p.user_id order by f.created_at desc limit 1),
         (select count(*) from public.flags f where f.user_id = p.user_id)::integer
    from public.players p
    join auth.users u on u.id = p.user_id
    left join public.profiles pr on pr.user_id = p.user_id
    left join public.clubs c on c.id = pr.club_id
   where p.locked_at is not null
   order by p.locked_at;
end;
$$;

create or replace function public.admin_unlock(p_user uuid)
returns void language plpgsql security definer set search_path = public as $$
begin
  perform public.require_admin();
  update public.players set locked_at = null, lock_reason = null, strikes = 0, strike_at = null where user_id = p_user;
  if not found then raise exception '계정을 찾을 수 없어요.' using errcode = 'P0001'; end if;
  update public.flags set resolved_at = now(), resolved_by = auth.uid() where user_id = p_user and resolved_at is null;
end;
$$;

-- 관리자 링크에 점을 찍는 데 쓴다
create or replace function public.locked_count()
returns integer language sql stable security definer set search_path = public as $$
  select case when public.admin_ok()
              then (select count(*) from public.players where locked_at is not null)::integer else 0 end
$$;


