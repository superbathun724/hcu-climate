-- ==========================================================
-- 04_study.sql — 단어 공부 기록과 코인
--
-- 03_game.sql 다음에 실행. 몇 번을 돌려도 같은 상태가 됩니다.
--
-- 규칙 (복습 날짜를 기다리지 않는다. 고른 단어장을 언제든, 고른 단계로 공부한다)
--   p_level = 이번 문제의 단계(학생이 고른 단계, "내 단계대로"면 그 단어의 지금 단계)
--   - 맞히면: 단계만큼 코인 (1·2·3·4·5·8) + 탭 에너지 (코인의 5배: 5·10·15·20·25·40)
--       p_level ≥ 지금 단계(도전) → p_level 의 다음 단계로 오른다(건너뛸 수 있다)
--       p_level < 지금 단계(복습) → 단계 그대로
--   - 틀리면: 복습(p_level ≤ 지금 단계)이면 한 단계 내려가고, 도전(p_level > 지금 단계)이면 그대로
--   - 코인은 고른 단계가 아니라 실제로 나온 문제 유형의 단계로 매긴다(p_pay).
--   - 같은 단어는 하루(한국 날짜)에 한 번만 코인을 받고 단계가 바뀐다.
--   - 그날 한 번 틀리거나 건너뛴 단어는(정답을 보여 주므로) 그날 다시 맞혀도 코인·단계가 그대로다.
--     → 같은 단어를 반복해서 코인을 불리는 길을 막는다. 하루 한도는 없다.
--
-- 자동 풀이(봇) 대비 — 사람은 거의 걸리지 않고, 걸려도 손해가 없게
--   1. 문제를 받은 지 1.5초 안에 들어온 정답은 코인을 주지 않는다. 단계·날짜도 그대로 두어
--      다시 풀면 코인을 받을 수 있다. (화면이 문제를 낼 때 issue_question 으로 시각을 남긴다)
--   2. 1분에 코인을 받는 정답은 20개까지. 넘으면 1번과 같이 채점만 하고 그대로 둔다.
--   3. 최근 20번의 답 간격이 기계처럼 일정하면(평균 12초 미만, 흔들림 8% 미만) 계정을 잠근다.
--      탭 매크로와 같이 관리자가 푼다.
--
-- 채점은 브라우저가 하지 않는다. functions/api/answer.js(Cloudflare)가 채점하고,
-- 비밀 키로 record_answer 를 부른다. 학생 계정은 record_answer 를 부를 수 없다.
-- ==========================================================

alter table public.progress add column if not exists last_correct_day date;
-- 오늘 틀린(건너뛴) 날. 같은 날 다시 맞혀도 코인을 주지 않는다(틀리면 정답을 보여 주므로).
alter table public.progress add column if not exists last_wrong_day date;

-- 문제를 낸 시각 (학생·단어마다 마지막 한 개만)
create table if not exists public.quiz_issues (
  user_id   uuid   not null references auth.users(id) on delete cascade,
  word_id   bigint not null references public.words(id) on delete cascade,
  issued_at timestamptz not null default now(),
  primary key (user_id, word_id)
);
-- 답한 시각 (1분 상한과 간격 검사에만 쓴다. 1시간 지난 것은 지운다)
create table if not exists public.answer_log (
  id      bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  at      timestamptz not null default now(),
  paid    boolean not null default false
);
create index if not exists answer_log_user_idx on public.answer_log (user_id, at);
alter table public.quiz_issues enable row level security;
alter table public.answer_log  enable row level security;
revoke all on public.quiz_issues, public.answer_log from anon, authenticated;   -- 아래 함수로만

create or replace function public.quiz_min_ms()    returns integer language sql immutable as $$ select 1500 $$;
create or replace function public.quiz_paid_per_min() returns integer language sql immutable as $$ select 20 $$;

-- 화면이 문제를 보여 줄 때 부른다
create or replace function public.issue_question(p_word bigint)
returns void language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then raise exception '로그인이 필요해요.' using errcode = '42501'; end if;
  insert into public.quiz_issues (user_id, word_id, issued_at) values (auth.uid(), p_word, now())
  on conflict (user_id, word_id) do update set issued_at = now();
end;
$$;

-- 단계별 코인 (js/quiz-core.js 의 COINS 와 같게)
create or replace function public.word_coins(p_level integer)
returns integer language sql immutable as $$
  select (array[1,2,3,4,5,8])[least(greatest(coalesce(p_level,0),0),5) + 1]
$$;

-- 단계별 에너지: 맞히면 코인과 함께 탭 에너지도 생긴다(에너지 1 = 탭 1번 = 1코인, 03_game.sql)
-- 코인의 5배. 1단계 5 · 2단계 10 · 3단계 15 · 4단계 20 · 5단계 25 · 6단계 40  (js/quiz-core.js ENERGY 와 같게)
create or replace function public.word_energy(p_level integer)
returns integer language sql immutable as $$ select 5 * public.word_coins(p_level) $$;

-- 예전 3칸짜리(단계 없이) 함수는 지운다. 남아 있으면 이름이 같은 함수가 둘이 된다.
-- 예전 함수(칸 수가 다른 것)는 지운다. 남아 있으면 이름이 같은 함수가 둘이 된다.
drop function if exists public.record_answer(uuid, bigint, boolean);
drop function if exists public.record_answer(uuid, bigint, boolean, smallint);

-- p_level: 고른 단계(단계 오르내림은 이것으로)
-- p_pay  : 코인을 매기는 단계 = 실제로 나온 문제 유형의 단계 (js/quiz-core.js coinLevel).
--          6단계를 골랐어도 자료가 없어 철자 문제가 나왔으면 2코인. 비우면 p_level 과 같다.
create or replace function public.record_answer(p_user uuid, p_word bigint, p_correct boolean, p_level smallint,
                                                p_pay smallint default null)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_today date := public.kst_today();
  pr public.progress;
  v_before smallint;
  v_lv smallint;
  v_coins integer := 0;
  v_energy integer := 0;
  v_energy_now integer;
  v_already boolean := false;
  v_balance numeric;
  v_issued timestamptz;
  v_throttle text;            -- null | 'fast' | 'busy'
  v_pays boolean;             -- 이번 답이 코인을 받는 답인가 (정답 + 오늘 아직 안 받았고 안 틀린 단어)
  v_n integer; v_mean numeric; v_sd numeric;
begin
  if not exists (select 1 from public.words w join public.word_sets s on s.id = w.set_id
                  where w.id = p_word and not s.hidden and s.deleted_at is null) then
    raise exception '단어를 찾을 수 없어요.' using errcode = 'P0001';
  end if;
  if not exists (select 1 from public.profiles where user_id = p_user) then
    raise exception '계정 정보를 찾을 수 없어요.' using errcode = 'P0001';
  end if;

  perform public.assert_unlocked(p_user);            -- 잠긴 계정은 단어 코인도 없음 (03_game.sql)
  perform public.ensure_player(p_user);

  insert into public.progress (user_id, word_id) values (p_user, p_word) on conflict do nothing;
  select * into pr from public.progress where user_id = p_user and word_id = p_word for update;
  v_before := pr.srs_level;
  v_lv := least(greatest(coalesce(p_level, pr.srs_level), 0), 5);

  -- 1·2. 너무 빠른 정답, 1분 상한 (코인을 받을 답에만 해당)
  select issued_at into v_issued from public.quiz_issues where user_id = p_user and word_id = p_word;
  delete from public.quiz_issues where user_id = p_user and word_id = p_word;      -- 한 문제에 한 번
  v_pays := p_correct and pr.last_correct_day is distinct from v_today and pr.last_wrong_day is distinct from v_today;
  if v_pays then
    if v_issued is null or now() - v_issued < make_interval(secs => public.quiz_min_ms() / 1000.0) then
      v_throttle := 'fast';
    elsif (select count(*) from public.answer_log
            where user_id = p_user and paid and at > now() - interval '60 seconds') >= public.quiz_paid_per_min() then
      v_throttle := 'busy';
    end if;
  end if;

  -- 3. 답 간격 검사 (정답·오답 모두)
  delete from public.answer_log where user_id = p_user and at < now() - interval '1 hour';
  insert into public.answer_log (user_id, paid) values (p_user, v_pays and v_throttle is null);
  select count(*), avg(gap), stddev_pop(gap) into v_n, v_mean, v_sd from (
    select extract(epoch from at - lag(at) over (order by at)) as gap
      from (select at from public.answer_log where user_id = p_user order by at desc limit 21) t
  ) g where gap is not null;
  if v_n >= 20 and v_mean < 12 and v_sd / nullif(v_mean, 0) < 0.08 then
    perform public.lock_player(p_user, 'quiz-pattern',
      jsonb_build_object('mean_s', round(v_mean, 2), 'cv', round(v_sd / v_mean, 3), 'n', v_n));
    select balance into v_balance from public.players where user_id = p_user;
    return jsonb_build_object('locked', true, 'correct', p_correct, 'coins', 0, 'balance', v_balance);
  end if;

  if v_throttle is not null then              -- 채점만. 단계·날짜 그대로라 다시 풀면 받는다
    select balance into v_balance from public.players where user_id = p_user;
    return jsonb_build_object(
      'correct', true, 'throttled', v_throttle, 'level_before', v_before, 'level', v_before,
      'asked', v_lv, 'coins', 0, 'already_today', false, 'balance', v_balance);
  end if;

  if p_correct then
    if pr.last_correct_day = v_today then
      v_already := true;                                  -- 오늘 이미 받음: 코인·단계 그대로
    elsif pr.last_wrong_day = v_today then
      null;                                               -- 오늘 한 번 틀림(건너뛰기 포함): 정답을 본 뒤라 코인·단계 그대로
    else
      v_coins  := public.word_coins(least(v_lv, coalesce(p_pay, v_lv)));
      v_energy := public.word_energy(least(v_lv, coalesce(p_pay, v_lv)));
      if v_lv >= pr.srs_level then
        pr.srs_level := least(v_lv + 1, 5);               -- 도전 성공: 고른 단계의 다음으로
      end if;
      pr.last_correct_day := v_today;
    end if;
  else
    if v_lv <= pr.srs_level then pr.srs_level := greatest(pr.srs_level - 1, 0); end if;   -- 복습에서 틀림: 한 단계만 내린다
    pr.wrong_count := pr.wrong_count + 1;
    if pr.last_correct_day is distinct from v_today then pr.last_wrong_day := v_today; end if;
  end if;

  update public.progress set
    srs_level        = pr.srs_level,
    last_correct_day = pr.last_correct_day,
    last_wrong_day   = pr.last_wrong_day,
    wrong_count      = pr.wrong_count,
    attempt_count    = attempt_count + 1,
    last_tested_at   = now()
  where user_id = p_user and word_id = p_word;

  update public.players
     set balance = balance + v_coins, earned_words = earned_words + v_coins, energy = energy + v_energy
   where user_id = p_user
  returning balance, energy into v_balance, v_energy_now;

  return jsonb_build_object(
    'correct', p_correct, 'level_before', v_before, 'level', pr.srs_level, 'asked', v_lv,
    'coins', v_coins, 'energy_gain', v_energy, 'energy', v_energy_now, 'already_today', v_already,
    'after_wrong', p_correct and not v_already and v_coins = 0,
    'balance', v_balance);
end;
$$;

-- 서버 함수(functions/api/answer.js)가 비밀 키로 단어와 단계를 읽는다.
-- 프로젝트를 "새 표 자동 공개 끔"으로 만들었기 때문에 service_role 에게도 따로 열어 줘야 한다.
grant select on public.words, public.word_sets, public.progress to service_role;

-- 서버 함수(비밀 키 = service_role)만 부를 수 있다.
revoke execute on function public.record_answer(uuid, bigint, boolean, smallint, smallint) from public, anon, authenticated;
grant  execute on function public.record_answer(uuid, bigint, boolean, smallint, smallint) to service_role;
