-- ==========================================================
-- 04_study.sql — 단어 공부 기록과 코인
--
-- 03_game.sql 다음에 실행. 몇 번을 돌려도 같은 상태가 됩니다.
--
-- 규칙 (복습 날짜를 기다리지 않는다. 고른 단어장을 언제든, 고른 단계로 공부한다)
--   p_level = 이번 문제의 단계(학생이 고른 단계, "내 단계대로"면 그 단어의 지금 단계)
--   - 맞히면: 단계만큼 코인 (1·2·3·4·5·8) + 탭 에너지 (코인의 100배: 100·200·300·400·500·800)
--       p_level ≥ 지금 단계(도전) → p_level 의 다음 단계로 오른다(건너뛸 수 있다)
--       p_level < 지금 단계(복습) → 단계 그대로
--   - 틀리면: 복습(p_level ≤ 지금 단계)이면 한 단계 내려가고, 도전(p_level > 지금 단계)이면 그대로
--   - 코인은 고른 단계가 아니라 실제로 나온 문제 유형의 단계로 매긴다(p_pay).
--   - 코인은 하루(한국 날짜)에 "한 단어 × 한 단계"마다 한 번. 같은 단어도 단계가 다르면 그날 또 받는다.
--     (단계 = 실제로 나온 문제 유형의 단계 p_pay. 6단계를 골라도 철자 문제가 나오면 2단계로 센다)
--   - 그날 그 단계에서 틀리거나 건너뛰면(정답을 보여 주므로) 그날 그 단계로는 다시 맞혀도 코인이 없다.
--     다른 단계는 그날도 받을 수 있다.
--   - 기록(progress.study_day, paid_levels, wrong_levels)은 날짜가 바뀌면 저절로 비워진 것으로 본다(매일 초기화).
--     → 같은 단어·같은 단계를 반복해서 코인을 불리는 길은 막는다. 하루 한도는 없다.
--
-- 자동 풀이(봇) 대비 — 사람은 거의 걸리지 않고, 걸려도 손해가 없게
--   1. 문제를 받은 지 1.5초 안에 들어온 정답은 코인을 주지 않는다. 단계·날짜도 그대로 두어
--      다시 풀면 코인을 받을 수 있다. (서버가 문제를 낼 때 issue_question_srv 로 시각을 남긴다)
--   2. 1분에 코인을 받는 정답은 20개까지. 넘으면 1번과 같이 채점만 하고 그대로 둔다.
--   3. 최근 30번의 답 간격이 기계처럼 일정하면(평균 8초 미만, 흔들림 3% 미만) 계정을 잠근다.
--   4. 문제는 서버(functions/api/question.js)가 낸다. 학생 화면에는 유의어·반의어·예문 같은 답이 오지 않고,
--      서버가 낸 유형이 아닌 답은 받지 않는다(쉬운 유형으로 바꿔 치기 못 함).
--   5. 답 길이에 맞춰 최소 시간이 늘어난다(1.5초 + 글자당 0.04초).
--   6. 붙여넣기 등으로 직접 타자를 치지 않은 답은 코인 없이 채점만 한다(p_typed).
--   7. 최근 40문제가 거의 다 맞고(97% 이상) 답하는 시간의 가운데 값이 2초 미만이면
--      10분 동안 코인만 쉬어 간다(잠그지 않는다. 채점·연습은 그대로).
--      사람은 문제마다 생각하는 시간이 달라 여기에 닿지 않는다.
--      탭 매크로와 같이 관리자가 푼다.
--
-- 채점은 브라우저가 하지 않는다. functions/api/answer.js(Cloudflare)가 채점하고,
-- 비밀 키로 record_answer 를 부른다. 학생 계정은 record_answer 를 부를 수 없다.
-- ==========================================================

